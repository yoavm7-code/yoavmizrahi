/* Yoav Mizrahi's portfolio. Plain JavaScript, no build step.
   The markup is generated by js/render.js; this file only adds behavior to it. */
(function () {
  'use strict';

  var $ = function (sel, root) { return (root || document).querySelector(sel); };
  var $$ = function (sel, root) { return Array.prototype.slice.call((root || document).querySelectorAll(sel)); };
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var narrow = window.matchMedia('(max-width: 900px)');

  function youtubeEmbed(id) {
    var f = document.createElement('iframe');
    f.className = 'embed';
    f.src = 'https://www.youtube-nocookie.com/embed/' + encodeURIComponent(id) + '?autoplay=1&rel=0';
    f.title = 'Film player';
    f.allow = 'autoplay; encrypted-media; picture-in-picture; fullscreen';
    f.allowFullscreen = true;
    return f;
  }
  function placeholderPlayer() {
    var d = document.createElement('div');
    d.className = 'placeholder-player';
    d.textContent = '[ THE FILM PLAYS HERE ONCE IT IS ON YOUTUBE ]';
    return d;
  }
  /* Shrinks a one-line title until it fits its box, so long film titles never spill or break. */
  function fitText(el) {
    el.style.fontSize = '';
    var box = el.parentNode;
    var cs = getComputedStyle(box);
    var room = box.clientWidth - parseFloat(cs.paddingLeft) - parseFloat(cs.paddingRight);
    if (room <= 0 || el.scrollWidth <= room) return;
    el.style.fontSize = Math.max(14, parseFloat(getComputedStyle(el).fontSize) * room / el.scrollWidth) + 'px';
  }

  /* ---------- Split headings into letters ---------- */
  $$('[data-split]').forEach(function (el) {
    var text = el.textContent;
    el.setAttribute('aria-label', text);
    el.textContent = '';
    var i = 0;
    text.split(' ').forEach(function (word, w) {
      if (w > 0) { el.appendChild(document.createTextNode(' ')); i++; }
      var wrap = document.createElement('span');
      wrap.className = 'word';
      wrap.setAttribute('aria-hidden', 'true');
      word.split('').forEach(function (ch) {
        var s = document.createElement('span');
        s.className = 'ltr';
        s.style.animationDelay = (150 + i * 35) + 'ms';
        s.textContent = ch;
        wrap.appendChild(s);
        i++;
      });
      el.appendChild(wrap);
    });
  });

  /* ---------- Router + page wipe ---------- */
  /* Routes come from the pages themselves: each section carries data-route, data-label and data-name.
     #/films/<id> opens the films page on that film (used by the share pages). */
  var routes = {};
  $$('.page[data-route]').forEach(function (p) {
    routes[p.getAttribute('data-route')] = { page: p.getAttribute('data-page'), label: p.getAttribute('data-label'), name: p.getAttribute('data-name') };
  });
  var siteTitle = document.body.getAttribute('data-site-title') || document.title;
  var siteName = document.body.getAttribute('data-site-name') || '';
  var wipe = $('[data-wipe]');
  var wipeLabel = $('[data-wipe-label]');
  var pageName = $('[data-page-name]');
  var current = null;
  var busy = false;

  function routeFromHash() {
    var h = (location.hash || '#/').replace(/^#/, '');
    if (routes[h]) return { path: h, film: null };
    var m = h.match(/^\/films\/([a-z0-9-]+)$/);
    if (m && routes['/films']) return { path: '/films', film: m[1] };
    return { path: '/', film: null };
  }
  function sameRoute(a, b) { return a.path === b.path && a.film === b.film; }

  function show(route) {
    var r = routes[route.path];
    var opening = current !== null;
    $$('.page').forEach(function (p) { p.classList.toggle('is-active', p.getAttribute('data-page') === r.page); });
    document.body.setAttribute('data-page', r.page);
    document.body.setAttribute('data-theme', r.page === 'films' ? 'dark' : 'light');
    pageName.textContent = r.name;
    document.title = (r.page === 'home' ? siteTitle : r.label + ' · ' + siteName);
    window.scrollTo(0, 0);
    onPageLeave(current);
    current = r.page;
    openReplicas(r.page);
    if (route.film) reelGoId(route.film);
    if (r.page === 'films') fitText($('[data-reel-title]'));
    if (r.page === 'home') layoutDesk();
    if (opening && !embedded) focusPage();
  }
  /* Keyboard and screen reader users land on the new page's heading, which reads out its name.
     Not inside a frame: in the admin's preview that would pull focus out of the field being edited. */
  var embedded = window.self !== window.top;
  function focusPage() {
    var h = $('.page.is-active h1');
    console.info('[site focus] page heading', { page: current, found: !!h });
    if (!h) return;
    h.setAttribute('tabindex', '-1');
    h.focus({ preventScroll: true });
  }
  $('[data-skip]').addEventListener('click', function (e) { e.preventDefault(); focusPage(); });

  function navigate() {
    var route = routeFromHash();
    var r = routes[route.path];
    closeMenu();
    if (current === null || reduceMotion) { show(route); return; }
    if (r.page === current || busy) {
      if (!busy) { if (route.film) reelGoId(route.film); else show(route); }
      return;
    }
    busy = true;
    setCursor('dot');
    wipeLabel.textContent = r.label;
    wipe.classList.remove('is-reveal');
    void wipe.offsetWidth;
    wipe.classList.add('is-cover');
    setTimeout(function () {
      show(route);
      wipe.classList.remove('is-cover');
      wipe.classList.add('is-reveal');
      setTimeout(function () {
        wipe.style.transition = 'none';
        wipe.classList.remove('is-reveal');
        void wipe.offsetWidth;
        wipe.style.transition = '';
        busy = false;
        if (!sameRoute(routeFromHash(), route)) navigate();
      }, 700);
    }, 650);
  }
  window.addEventListener('hashchange', navigate);

  /* ---------- Menu ---------- */
  /* While the menu is open everything behind it is inert, so Tab stays in the menu. Closing it hands
     focus back to the Menu button, unless a menu link already moved on to a new page. */
  var menu = $('#menu');
  var menuButton = $('.site-header [data-menu-toggle]');
  var behindMenu = [$('.site-header'), $('main'), $('[data-skip]')];
  menu.inert = true;
  function setMenu(open) {
    var wasOpen = document.body.classList.contains('menu-open');
    var hadFocus = menu.contains(document.activeElement);
    document.body.classList.toggle('menu-open', open);
    menu.setAttribute('aria-hidden', open ? 'false' : 'true');
    menu.inert = !open;
    behindMenu.forEach(function (el) { el.inert = open; });
    $$('[data-menu-toggle]').forEach(function (b) { b.setAttribute('aria-expanded', open ? 'true' : 'false'); });
    if (open && !wasOpen) $('.mlink', menu).focus();
    if (!open && wasOpen && hadFocus) menuButton.focus();
    if (open !== wasOpen) console.info('[site menu]', { open: open, focusBack: !open && hadFocus });
  }
  function closeMenu() { setMenu(false); }
  $$('[data-menu-toggle]').forEach(function (b) {
    b.addEventListener('click', function () { setMenu(!document.body.classList.contains('menu-open')); });
  });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape' && document.body.classList.contains('menu-open')) closeMenu(); });

  /* ---------- Custom cursor (fine pointers only) ---------- */
  var cursor = $('[data-cursor-el]');
  var cursorText = $('[data-cursor-text]');
  var dragging = null;
  function setCursor(mode) {
    if (mode === 'dot') { cursor.classList.remove('is-big'); return; }
    cursorText.textContent = mode === 'drag' ? 'DRAG' : 'VIEW';
    cursor.classList.add('is-big');
  }
  if (window.matchMedia('(pointer: fine)').matches) {
    document.documentElement.classList.add('has-cursor');
    var cx = -100, cy = -100, tx = -100, ty = -100;
    window.addEventListener('pointermove', function (e) { tx = e.clientX; ty = e.clientY; }, { passive: true });
    (function loop() {
      cx += (tx - cx) * 0.35; cy += (ty - cy) * 0.35;
      cursor.style.transform = 'translate(' + cx + 'px,' + cy + 'px)';
      requestAnimationFrame(loop);
    })();
    document.addEventListener('pointerover', function (e) {
      if (dragging) return;
      var el = e.target.closest('[data-cursor]');
      if (!el || e.target.closest('button, a:not([data-cursor])')) { setCursor('dot'); return; }
      setCursor(el.getAttribute('data-cursor'));
    });
  }

  /* ---------- Uploader demo: a pocket Launch (all instances share state) ---------- */
  /* The rows are campaigns from the replica's recorded launch (demos/launch-desk), so the desk matches the
     video. Credit Cards fails on the financial claims policy there too. */
  var upRows = [
    { name: 'CA · Smart Home' }, { name: 'FR · Meal Kits' }, { name: 'IT · Language Apps' },
    { name: 'AU · Credit Cards', fails: true }, { name: 'NL · Pet Food' }
  ];
  var upText = { ready: 'ready', running: 'launching', live: 'live', failed: 'policy' };
  var up = { done: 0, running: false, timer: null };
  function upState(i) {
    if (i < up.done) return upRows[i].fails ? 'failed' : 'live';
    return up.running && i === up.done ? 'running' : 'ready';
  }
  /* Builds a widget's rows once, so the polite summary stays the same node and is announced. */
  function buildUploader(root) {
    var list = document.createElement('ul');
    list.className = 'u-rows';
    upRows.forEach(function (r) {
      var li = document.createElement('li');
      li.className = 'u-row';
      li.innerHTML = '<span class="u-dot" aria-hidden="true"></span><span class="u-name"></span><span class="u-state"></span>';
      $('.u-name', li).textContent = r.name;
      list.appendChild(li);
    });
    var foot = document.createElement('div');
    foot.className = 'u-foot';
    foot.innerHTML = '<button class="btn u-btn" type="button" data-u-start></button><span class="u-sum" aria-live="polite"></span>';
    root.replaceChildren(list, foot);
  }
  function renderUploader() {
    var live = 0, failed = 0;
    upRows.forEach(function (r, i) { var st = upState(i); if (st === 'live') live++; if (st === 'failed') failed++; });
    var started = up.running || up.done > 0;
    $$('[data-upload-led]').forEach(function (el) { el.classList.toggle('is-on', up.running); });
    $$('[data-widget="uploader"]').forEach(function (root) {
      if (!$('.u-rows', root)) buildUploader(root);
      $$('.u-row', root).forEach(function (li, i) {
        var st = upState(i);
        li.className = 'u-row is-' + st;
        $('.u-state', li).textContent = upText[st];
      });
      var btn = $('[data-u-start]', root);
      btn.textContent = up.running ? 'LAUNCHING…' : started ? 'LAUNCH AGAIN' : 'LAUNCH';
      btn.disabled = up.running;
      $('.u-sum', root).textContent = started ? live + ' live · ' + failed + ' failed' : upRows.length + ' campaigns ready';
    });
  }
  document.addEventListener('click', function (e) {
    if (!e.target.closest('[data-u-start]') || up.running) return;
    clearInterval(up.timer);
    up.done = 0;
    up.running = true;
    renderUploader();
    up.timer = setInterval(function () {
      up.done++;
      if (up.done >= upRows.length) { up.running = false; clearInterval(up.timer); }
      renderUploader();
    }, 520);
  });
  renderUploader();

  /* ---------- Work cards: the product's video plays on hover ---------- */
  /* Nothing loads until the first hover. Touch screens and reduced motion keep the still poster. */
  if (window.matchMedia('(hover: hover) and (pointer: fine)').matches && !reduceMotion) {
    $$('[data-card-video]').forEach(function (video) {
      var card = video.closest('.card');
      card.addEventListener('mouseenter', function () {
        if (!video.src) video.src = video.getAttribute('data-src');
        var played = video.play();
        if (played && played.catch) played.catch(function () {});
        card.classList.add('is-playing');
      });
      card.addEventListener('mouseleave', function () { video.pause(); card.classList.remove('is-playing'); });
    });
  }

  /* ---------- Toto demo: a pocket match pick (all instances share state) ---------- */
  /* The replica's main moment, small: Brazil vs Japan, + and - set the score, and it saves by itself
     after a pause, with undo, as in the video. The dice picks a random score. */
  var TOTO_TEAMS = ['Brazil', 'Japan'];
  var toto = { pick: null, saved: null, undoTo: undefined, state: 'none', timer: null };
  function totoScore(s) { return s[0] + '-' + s[1]; }
  /* Builds a widget once, so focus stays on the button that was pressed and the status is announced. */
  function buildToto(root) {
    var card = document.createElement('div');
    card.className = 'toto__card';
    card.innerHTML = '<span class="toto__when">TODAY · 18:00</span>';
    TOTO_TEAMS.forEach(function (name, side) {
      var row = document.createElement('div');
      row.className = 'toto__row';
      row.innerHTML = '<span class="toto__name"></span>' +
        '<button class="btn toto__step" type="button" data-t="' + side + ':-1">−</button>' +
        '<b class="toto__goals" data-goals="' + side + '"></b>' +
        '<button class="btn toto__step" type="button" data-t="' + side + ':1">+</button>';
      row.querySelector('.toto__name').textContent = name;
      row.querySelectorAll('[data-t]').forEach(function (btn, k) { btn.setAttribute('aria-label', name + (k ? ': one goal more' : ': one goal fewer')); });
      card.appendChild(row);
    });
    var foot = document.createElement('div');
    foot.className = 'toto__foot';
    foot.innerHTML = '<span class="toto__status" role="status" aria-live="polite"></span>' +
      '<button class="btn toto__dice" type="button" data-t="dice" aria-label="Surprise me: a random score">🎲</button>';
    root.replaceChildren(card, foot, Object.assign(document.createElement('span'), { className: 'toto__rule', textContent: 'EXACT +10 · DIRECTION +5' }));
  }
  function renderToto() {
    var shown = toto.pick || [0, 0];
    $$('[data-widget="toto"]').forEach(function (root) {
      if (!$('.toto__card', root)) buildToto(root);
      root.classList.toggle('is-empty', !toto.pick);
      $$('[data-goals]', root).forEach(function (el) { el.textContent = String(shown[+el.getAttribute('data-goals')]); });
      $$('[data-t$=":-1"]', root).forEach(function (btn) { btn.disabled = !toto.pick || shown[+btn.getAttribute('data-t').charAt(0)] === 0; });
      var status = $('.toto__status', root);
      if (toto.state === 'pending' || toto.state === 'saving') status.innerHTML = '<span class="toto__spin" aria-hidden="true"></span>Saving…';
      else if (toto.state === 'saved') {
        status.textContent = '✓ Saved ' + totoScore(toto.saved);
        if (toto.undoTo !== undefined) status.insertAdjacentHTML('beforeend', ' <button class="toto__undo" type="button" data-t="undo">Undo</button>');
      } else status.textContent = toto.state === 'removed' ? 'Pick removed' : 'No pick yet';
    });
  }
  /* Every change waits a moment, then saves. The first change after a save remembers what to undo to. */
  function setToto(pick) {
    if (toto.state !== 'pending' && toto.state !== 'saving') toto.undoTo = toto.saved;
    toto.pick = pick;
    toto.state = 'pending';
    clearTimeout(toto.timer);
    toto.timer = setTimeout(function () {
      toto.state = 'saving';
      renderToto();
      toto.timer = setTimeout(function () { toto.saved = toto.pick.slice(); toto.state = 'saved'; renderToto(); }, 450);
    }, 600);
    renderToto();
  }
  document.addEventListener('click', function (e) {
    var b = e.target.closest('[data-t]');
    if (!b) return;
    var a = b.getAttribute('data-t');
    if (a === 'undo') {
      clearTimeout(toto.timer);
      toto.pick = toto.undoTo ? toto.undoTo.slice() : null;
      toto.saved = toto.pick;
      toto.state = toto.pick ? 'saved' : 'removed';
      toto.undoTo = undefined;
      renderToto();
    } else if (a === 'dice') {
      setToto([Math.floor(Math.random() * 4), Math.floor(Math.random() * 4)]);
    } else {
      var p = a.split(':');
      var next = (toto.pick || [0, 0]).slice();
      next[+p[0]] = Math.max(0, Math.min(9, next[+p[0]] + parseInt(p[1], 10)));
      setToto(next);
    }
  });
  renderToto();

  /* ---------- Replicas: the real product on its project page ---------- */
  /* The interactive copy loads only when its page opens, renders at its real size and is scaled down
     to fit the device. Narrow screens get the recorded video; the copy stays one link away. */
  var replicas = $$('[data-replica]').map(function (box) {
    var viewport = $('[data-replica-viewport]', box);
    var video = $('[data-replica-video]', box);
    var w = +box.getAttribute('data-w');
    var h = +box.getAttribute('data-h');
    /* A responsive site can also be shown at phone size; the copy is resized, so it reflows. */
    var sizes = { desktop: [w, h], phone: box.hasAttribute('data-phone-w') ? [+box.getAttribute('data-phone-w'), +box.getAttribute('data-phone-h')] : null };
    var view = 'desktop';
    var page = box.closest('.page').getAttribute('data-page');
    var frame = null;
    /* The screen takes the replica's own shape. Set here, not in the markup: the admin's preview
       allows no inline styles. */
    viewport.style.aspectRatio = video.style.aspectRatio = w + ' / ' + h;

    function log(msg, values) { console.info('[site replica] ' + msg, values || {}); }
    function load() {
      if (frame) return;
      frame = document.createElement('iframe');
      frame.className = 'replica__frame';
      frame.title = box.getAttribute('data-title') + ', interactive demo';
      frame.width = w;
      frame.height = h;
      /* No allow-same-origin: the copy runs as an outside page, with no reach into the site, its storage
         or the admin. It reads site.json and its own files the way any other site could. */
      frame.setAttribute('sandbox', 'allow-scripts allow-downloads');
      frame.setAttribute('allow', 'clipboard-write');
      frame.addEventListener('load', function () { log('loaded', { src: frame.src }); });
      frame.src = box.getAttribute('data-src');
      viewport.appendChild(frame);
      fit();
      log('loading', { src: frame.src, width: w, height: h });
    }
    function fit() {
      if (!frame || !viewport.clientWidth) return;
      var s = viewport.clientWidth / w;
      frame.style.transform = 'scale(' + s + ')';
      log('fit', { scale: Math.round(s * 1000) / 1000 });
    }
    function setMode(mode) {
      box.setAttribute('data-mode', mode);
      $$('[data-replica-mode]', box).forEach(function (b) { b.setAttribute('aria-pressed', b.getAttribute('data-replica-mode') === mode ? 'true' : 'false'); });
      layout();
      if (mode === 'try') { video.pause(); load(); fit(); }
      else { var played = video.play(); if (played && played.catch) played.catch(function (e) { log('video did not autoplay', { reason: e.name }); }); }
      log('mode', { page: page, mode: mode, narrow: narrow.matches });
    }
    /* The phone view shapes the device like a phone while trying it; the video is always the
       desktop recording, so watching uses the wide device. */
    function setView(next) {
      if (!sizes.phone) return;
      view = next;
      w = sizes[view][0];
      h = sizes[view][1];
      viewport.style.aspectRatio = w + ' / ' + h;
      if (frame) { frame.width = w; frame.height = h; }
      $$('[data-replica-view]', box).forEach(function (b) { b.setAttribute('aria-pressed', b.getAttribute('data-replica-view') === view ? 'true' : 'false'); });
      layout();
      fit();
      log('view', { page: page, view: view });
    }
    function layout() {
      if (!sizes.phone) return;
      var phoneLook = view === 'phone' && box.getAttribute('data-mode') === 'try';
      box.classList.toggle('replica--phone', phoneLook);
      box.setAttribute('data-frame', phoneLook ? 'phone' : 'desktop');
    }
    $$('[data-replica-mode]', box).forEach(function (b) {
      b.addEventListener('click', function () { setMode(b.getAttribute('data-replica-mode')); });
    });
    $$('[data-replica-view]', box).forEach(function (b) {
      b.addEventListener('click', function () { setView(b.getAttribute('data-replica-view')); });
    });
    $('[data-replica-reset]', box).addEventListener('click', function () {
      if (frame) { frame.src = box.getAttribute('data-src'); log('start over', { page: page }); } else load();
    });
    viewport.addEventListener('mouseenter', function () { document.documentElement.classList.add('cursor-off'); });
    viewport.addEventListener('mouseleave', function () { document.documentElement.classList.remove('cursor-off'); });
    if (window.ResizeObserver) new ResizeObserver(fit).observe(viewport);
    else window.addEventListener('resize', fit);

    return {
      page: page,
      /* A desktop replica is too small to use on a narrow screen; a phone replica is made for one,
         and a site with a phone view opens in it. */
      open: function () {
        if (sizes.phone && narrow.matches && view !== 'phone') setView('phone');
        setMode(narrow.matches && !sizes.phone && box.getAttribute('data-frame') !== 'phone' ? 'watch' : box.getAttribute('data-mode'));
      },
      close: function () { video.pause(); document.documentElement.classList.remove('cursor-off'); }
    };
  });
  function openReplicas(page) { replicas.forEach(function (r) { if (r.page === page) r.open(); }); }
  narrow.addEventListener('change', function () { openReplicas(current); });

  /* ---------- The desk: layout, dragging, tapes, monitor ---------- */
  /* Wider than 900px, js/desk-layout.js places everything in the desk order: the note, the film
     corner (the monitor with its tapes piled beside it) and the works. Up to 900px the desk is a
     pile you scroll through (CSS). Anything can be dragged anywhere on the desk, with a mouse
     straight away and on touch after a short press and hold, so a quick swipe still scrolls.
     A drag adds an offset to the object's home spot; Tidy up takes the offsets away. */
  var Layout = window.DeskLayout;
  var desk = $('[data-desk]');
  var objs = $$('.obj', desk);
  var monitorObj = $('[data-obj="monitor"]', desk);
  var tapes = $$('[data-tape]', desk);
  var screen = $('[data-monitor]');
  var monitorPlayer = $('[data-monitor-player]');
  var ejectBtn = $('[data-eject]');
  var power = $('[data-power]');
  var tidyBtn = $('[data-tidy]');
  var z = objs.length + 1;
  var tapeIn = null;

  var GAP = 40;          // between objects on the desk
  var CORNER_GAP = 28;   // between the monitor and its tapes
  var HINT_ROOM = 56;    // kept free under the objects for the hint line
  var HOLD_MS = 350;     // press and hold on touch before an object lifts
  var SLOP = 8;          // movement that turns a press into a scroll instead

  var offsets = {};      // key -> { dx, dy } added by dragging
  var sizes = {};        // key -> { w, h } measured before any tilt
  var layers = {};       // key -> the object's stacking layer at home, in page order
  objs.forEach(function (o, i) {
    offsets[keyOf(o)] = { dx: 0, dy: 0 };
    layers[keyOf(o)] = i + 1;
    o.style.zIndex = i + 1;
  });

  function keyOf(o) { return o.getAttribute('data-obj'); }
  function lean(o) {
    var key = keyOf(o);
    if (key === 'monitor') return 0;
    var r = Layout.tilt(key);
    if (o.hasAttribute('data-tape') || narrow.matches) r = r * 2 / 3;
    return Math.round(r * 4) / 4;
  }
  function rest(o) {
    var off = offsets[keyOf(o)];
    o.style.transform = (off.dx || off.dy ? 'translate(' + off.dx + 'px,' + off.dy + 'px) ' : '') + 'rotate(' + lean(o) + 'deg)';
  }
  /* Back on its home layer, so a pile of tapes stacks the same way it did before anything moved. */
  function layerHome(o) { o.style.zIndex = layers[keyOf(o)]; }
  function measure(o) {
    var key = keyOf(o);
    if (!sizes[key] && o.offsetWidth) sizes[key] = { w: o.offsetWidth, h: o.offsetHeight };
    return sizes[key];
  }

  function layoutDesk() {
    if (!fontsReady || !desk.offsetWidth) return;
    if (narrow.matches) {
      desk.style.height = '';
      objs.forEach(function (o) { o.style.left = ''; o.style.top = ''; rest(o); });
      return;
    }
    objs.forEach(measure);
    var tapeSize = tapes.map(function (t) { return sizes[keyOf(t)]; }).filter(Boolean)[0];
    var count = tapeSize ? tapes.length : 0;
    var view = desk.parentNode.clientHeight - HINT_ROOM;
    /* The film corner has two shapes (tapes beside the monitor, or under it); keep the better desk. */
    var best = null;
    ['beside', 'below'].forEach(function (shape) {
      var corner = Layout.filmCorner(sizes.monitor, tapeSize || { w: 0, h: 0 }, count, CORNER_GAP, shape);
      var blocks = [];
      objs.forEach(function (o) {
        var key = keyOf(o);
        if (o.hasAttribute('data-tape')) return;
        if (key === 'monitor') blocks.push({ key: key, w: corner.w, h: corner.h, r: 0 });
        else if (sizes[key]) blocks.push({ key: key, w: sizes[key].w, h: sizes[key].h, r: lean(o) });
      });
      var result = Layout.arrange(blocks, desk.offsetWidth, view, { gap: GAP });
      if (!best || Layout.better(result, best.result)) best = { shape: shape, corner: corner, blocks: blocks, result: result };
    });
    var corner = best.corner, result = best.result;
    function put(o, x, y) { o.style.left = x + 'px'; o.style.top = y + 'px'; rest(o); }
    objs.forEach(function (o) {
      var key = keyOf(o);
      if (result.pos[key]) put(o, result.pos[key].x, result.pos[key].y);
    });
    var at = result.pos.monitor;
    if (at) put(monitorObj, at.x + corner.monitor.x, at.y + corner.monitor.y);
    tapes.forEach(function (t, i) { if (at && corner.tapes[i]) put(t, at.x + corner.tapes[i].x, at.y + corner.tapes[i].y); });
    desk.style.height = (result.height + HINT_ROOM) + 'px';
    desk.classList.add('is-laid');
    console.info('[desk layout]', { width: desk.offsetWidth, objects: best.blocks.length, tapes: count, films: best.shape, fits: result.fits, height: result.height });
  }

  var layoutFrame = 0;
  function relayout() { cancelAnimationFrame(layoutFrame); layoutFrame = requestAnimationFrame(layoutDesk); }
  window.addEventListener('resize', relayout);
  narrow.addEventListener('change', relayout);

  /* The note's handwriting changes its size, so the first layout waits for the fonts (at most
     FONT_WAIT), and the desk fades in once. Fonts that arrive later re-measure and re-place. */
  var FONT_WAIT = 1500;
  var fontsReady = !document.fonts;
  function onFonts(late) {
    if (fontsReady && !late) return;
    if (late) sizes = {};
    fontsReady = true;
    console.info('[desk layout] fonts', { late: !!late });
    relayout();
  }
  if (document.fonts) {
    var fontTimer = setTimeout(function () { onFonts(false); }, FONT_WAIT);
    document.fonts.ready.then(function () { var late = fontsReady; clearTimeout(fontTimer); onFonts(late); });
  }
  layoutDesk();

  /* ---------- Dragging ---------- */
  function setOffset(o, dx, dy) { offsets[keyOf(o)] = { dx: Math.round(dx), dy: Math.round(dy) }; }
  function anyMoved() {
    return objs.some(function (o) { var f = offsets[keyOf(o)]; return (f.dx || f.dy) && !o.classList.contains('is-inserted'); });
  }
  function showTidy() { tidyBtn.hidden = !anyMoved(); }

  function lift(d) {
    var o = d.o;
    d.lifted = true;
    var box = o.getBoundingClientRect(), room = desk.getBoundingClientRect();
    d.min = { x: room.left - box.left, y: room.top - box.top };
    d.max = { x: room.right - box.right, y: room.bottom - box.bottom };
    o.style.zIndex = ++z;
    o.classList.add('is-dragging');
    o.style.transform = 'translate(' + d.dx + 'px,' + d.dy + 'px) rotate(0deg) scale(1.04)';
    if (d.touch && navigator.vibrate) navigator.vibrate(8);
  }
  /* A tape counts as dropped on the monitor when the pointer or the tape's middle is over it. */
  function drop(d, px, py) {
    var o = d.o;
    o.classList.remove('is-dragging');
    rest(o);
    showTidy();
    var off = offsets[keyOf(o)];
    if (!off.dx && !off.dy) layerHome(o);
    console.info('[desk drag]', { key: keyOf(o), dx: off.dx, dy: off.dy });
    if (o.hasAttribute('data-tape')) {
      var t = o.getBoundingClientRect(), m = monitorObj.getBoundingClientRect();
      function over(x, y) { return x > m.left && x < m.right && y > m.top && y < m.bottom; }
      if (over(px, py) || over(t.left + t.width / 2, t.top + t.height / 2)) {
        console.info('[desk drag] tape dropped on the monitor', { key: keyOf(o) });
        insertTape(o);
      }
    }
  }

  objs.forEach(function (o) {
    o.addEventListener('pointerdown', function (e) {
      if (dragging || e.button !== 0 || e.target.closest('button, a, input, select, textarea, iframe, video')) return;
      var off = offsets[keyOf(o)];
      var d = { o: o, id: e.pointerId, sx: e.clientX, sy: e.clientY, dx: off.dx, dy: off.dy, touch: e.pointerType === 'touch', lifted: false };
      dragging = d;
      if (d.touch) {
        d.timer = setTimeout(function () { if (dragging === d) lift(d); }, HOLD_MS);
      } else {
        e.preventDefault();
        o.setPointerCapture(e.pointerId);
        lift(d);
      }
    });
    o.addEventListener('contextmenu', function (e) { if (dragging && dragging.o === o) e.preventDefault(); });
  });
  window.addEventListener('pointermove', function (e) {
    var d = dragging;
    if (!d || e.pointerId !== d.id) return;
    var mx = e.clientX - d.sx, my = e.clientY - d.sy;
    if (!d.lifted) {
      if (Math.abs(mx) > SLOP || Math.abs(my) > SLOP) { clearTimeout(d.timer); dragging = null; }
      return;
    }
    setOffset(d.o, d.dx + Math.max(d.min.x, Math.min(d.max.x, mx)), d.dy + Math.max(d.min.y, Math.min(d.max.y, my)));
    var off = offsets[keyOf(d.o)];
    d.o.style.transform = 'translate(' + off.dx + 'px,' + off.dy + 'px) rotate(0deg) scale(1.04)';
  });
  function endDrag(e) {
    var d = dragging;
    if (!d || e.pointerId !== d.id) return;
    clearTimeout(d.timer);
    dragging = null;
    if (d.lifted) drop(d, e.clientX, e.clientY);
  }
  window.addEventListener('pointerup', endDrag);
  window.addEventListener('pointercancel', endDrag);
  /* Once something is lifted on touch, the finger moves it instead of scrolling the page. */
  document.addEventListener('touchmove', function (e) { if (dragging && dragging.lifted) e.preventDefault(); }, { passive: false });

  tidyBtn.addEventListener('click', function () {
    var count = 0;
    objs.forEach(function (o) {
      var off = offsets[keyOf(o)];
      if (o.classList.contains('is-inserted')) return;
      layerHome(o);
      if (!off.dx && !off.dy) return;
      var delay = count++ * 40;
      setOffset(o, 0, 0);
      if (!reduceMotion) {
        o.style.transitionDelay = delay + 'ms';
        o.classList.add('is-tidying');
        setTimeout(function () { o.classList.remove('is-tidying'); o.style.transitionDelay = ''; }, 700 + delay);
      }
      rest(o);
    });
    tidyBtn.hidden = true;
    console.info('[desk tidy]', { moved: count });
  });

  /* ---------- Tapes and the monitor ---------- */
  function setScreen(state) { screen.setAttribute('data-state', state); }
  function insertTape(tape) {
    if (tapeIn && tapeIn !== tape) returnTape(tapeIn);
    tapeIn = tape;
    tape.classList.add('is-inserted');
    $('[data-monitor-presents]').textContent = tape.getAttribute('data-presents');
    $('[data-monitor-title]').textContent = tape.getAttribute('data-title');
    $('[data-monitor-part]').textContent = tape.getAttribute('data-part');
    monitorPlayer.innerHTML = '';
    var idle = $('.monitor__idle', screen);
    idle.classList.remove('tv-on'); void idle.offsetWidth; idle.classList.add('tv-on');
    setScreen('idle');
    fitText($('[data-monitor-title]'));
    ejectBtn.classList.add('is-visible');
    power.classList.add('is-on');
    showTidy();
    if (narrow.matches) monitorObj.scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'center' });
  }
  /* An ejected tape goes back to its place in the pile. */
  function returnTape(tape) {
    tape.classList.remove('is-inserted');
    setOffset(tape, 0, 0);
    layerHome(tape);
    rest(tape);
    showTidy();
  }
  function eject() {
    if (!tapeIn) return;
    returnTape(tapeIn);
    tapeIn = null;
    monitorPlayer.innerHTML = '';
    setScreen('empty');
    ejectBtn.classList.remove('is-visible');
    power.classList.remove('is-on');
  }
  $$('[data-insert]', desk).forEach(function (b) {
    b.addEventListener('click', function () { insertTape(b.closest('.obj')); });
  });
  ejectBtn.addEventListener('click', eject);
  $('[data-monitor-play]').addEventListener('click', function () {
    if (!tapeIn) return;
    var id = tapeIn.getAttribute('data-youtube');
    monitorPlayer.innerHTML = '';
    monitorPlayer.appendChild(id ? youtubeEmbed(id) : placeholderPlayer());
    setScreen('playing');
  });

  /* ---------- Films: the reel ---------- */
  var clips = $$('[data-clip]');
  var ruler = $('[data-scrub]');
  var playhead = $('[data-playhead]');
  var scene = $('[data-reel-scene]');
  var reelPlayer = $('[data-reel-player]');
  var toggleBtn = $('[data-reel-toggle]');
  var reel = { pos: 0, idx: -1, timer: null };
  var REEL_SECONDS = 150;

  for (var i = 0; i <= 30; i++) {
    var tick = document.createElement('span');
    tick.style.left = (i / 30 * 100) + '%';
    if (i % 6 === 0) tick.className = 'major';
    ruler.appendChild(tick);
  }
  clips.forEach(function (c) {
    var s = +c.getAttribute('data-start'), e = +c.getAttribute('data-end');
    c.style.left = 'calc(' + (s * 100) + '% + 2px)';
    c.style.width = 'calc(' + ((e - s) * 100) + '% - 4px)';
    c.addEventListener('click', function () { reelStop(); reelGo(clips.indexOf(c)); });
  });

  function pad(n) { return (n < 10 ? '0' : '') + n; }
  function clipAt(p) {
    for (var k = 0; k < clips.length; k++) if (p < +clips[k].getAttribute('data-end')) return k;
    return clips.length - 1;
  }
  function renderReel() {
    var secs = reel.pos * REEL_SECONDS;
    $('[data-timecode]').textContent = '00:' + pad(Math.floor(secs / 60)) + ':' + pad(Math.floor(secs % 60)) + ':' + pad(Math.floor((secs % 1) * 24));
    playhead.style.left = (reel.pos * 100) + '%';
    ruler.setAttribute('aria-valuenow', Math.floor(secs));
    ruler.setAttribute('aria-valuetext', Math.floor(secs) + ' seconds' + (clips.length ? ', ' + clips[clipAt(Math.min(reel.pos, 0.9999))].getAttribute('data-label') : ''));
    if (!clips.length) return;
    var idx = clipAt(Math.min(reel.pos, 0.9999));
    if (idx !== reel.idx) {
      reel.idx = idx;
      var c = clips[idx];
      clips.forEach(function (x, k) { x.classList.toggle('is-active', k === idx); x.setAttribute('aria-pressed', k === idx ? 'true' : 'false'); });
      $('[data-reel-presents]').textContent = c.getAttribute('data-presents');
      $('[data-reel-title]').textContent = c.getAttribute('data-title');
      $('[data-reel-part]').textContent = c.getAttribute('data-part');
      $('[data-reel-file]').textContent = c.getAttribute('data-file');
      $('[data-reel-label]').textContent = [c.getAttribute('data-label'), c.getAttribute('data-meta')].filter(Boolean).join(' · ');
      scene.classList.remove('is-playing', 'scene-in');
      scene.classList.toggle('is-soon', c.hasAttribute('data-soon'));
      reelPlayer.innerHTML = '';
      void scene.offsetWidth;
      scene.classList.add('scene-in');
      fitText($('[data-reel-title]'));
    }
  }
  function reelGo(k) {
    if (!clips.length) return;
    k = Math.max(0, Math.min(clips.length - 1, k));
    playhead.classList.remove('is-running');
    reel.pos = +clips[k].getAttribute('data-start');
    reel.idx = -1;
    renderReel();
  }
  function reelGoId(id) {
    var k = clips.map(function (c) { return c.getAttribute('data-id'); }).indexOf(id);
    if (k !== -1) { reelStop(); reelGo(k); }
  }
  function reelStop() {
    clearInterval(reel.timer); reel.timer = null;
    toggleBtn.classList.remove('is-playing');
    toggleBtn.setAttribute('aria-label', 'Play reel');
  }
  function reelPlay() {
    if (!clips.length) return;
    if (reel.pos >= 0.999) reelGo(0);
    scene.classList.remove('is-playing');
    reelPlayer.innerHTML = '';
    playhead.classList.add('is-running');
    toggleBtn.classList.add('is-playing');
    toggleBtn.setAttribute('aria-label', 'Pause reel');
    reel.timer = setInterval(function () {
      reel.pos += 0.1 / 30;
      if (reel.pos >= 1) { reel.pos = 1; reelStop(); }
      renderReel();
    }, 100);
  }
  toggleBtn.addEventListener('click', function () { if (reel.timer) reelStop(); else reelPlay(); });
  $('[data-reel-prev]').addEventListener('click', function () { reelStop(); reelGo(reel.idx - 1); });
  $('[data-reel-next]').addEventListener('click', function () { reelStop(); reelGo(reel.idx + 1); });
  function reelSeek(p) {
    reelStop();
    playhead.classList.remove('is-running');
    reel.pos = Math.max(0, Math.min(0.999, p));
    renderReel();
  }
  ruler.addEventListener('click', function (e) {
    var r = ruler.getBoundingClientRect();
    reelSeek((e.clientX - r.left) / r.width);
  });
  /* The ruler is a slider: arrows move 5 seconds, Page Up and Down 30, Home and End to either end. */
  var SCRUB_KEYS = { ArrowRight: 5, ArrowUp: 5, ArrowLeft: -5, ArrowDown: -5, PageUp: 30, PageDown: -30 };
  ruler.addEventListener('keydown', function (e) {
    var step = SCRUB_KEYS[e.key];
    if (e.key === 'Home') reelSeek(0);
    else if (e.key === 'End') reelSeek(1);
    else if (step) reelSeek(reel.pos + step / REEL_SECONDS);
    else return;
    e.preventDefault();
    console.info('[site reel] key', { key: e.key, seconds: Math.floor(reel.pos * REEL_SECONDS) });
  });
  $('[data-reel-filmplay]').addEventListener('click', function () {
    if (!clips[reel.idx]) return;
    reelStop();
    var id = clips[reel.idx].getAttribute('data-youtube');
    reelPlayer.innerHTML = '';
    reelPlayer.appendChild(id ? youtubeEmbed(id) : placeholderPlayer());
    scene.classList.add('is-playing');
  });
  renderReel();

  function refitTitles() {
    fitText($('[data-reel-title]'));
    fitText($('[data-monitor-title]'));
  }
  window.addEventListener('resize', refitTitles);
  if (document.fonts) document.fonts.ready.then(refitTitles);

  /* Stop anything playing when leaving a page. */
  function onPageLeave(page) {
    replicas.forEach(function (r) { if (r.page === page) r.close(); });
    if (page === 'films') { reelStop(); reelPlayer.innerHTML = ''; scene.classList.remove('is-playing'); }
    if (page === 'home' && screen.getAttribute('data-state') === 'playing') { monitorPlayer.innerHTML = ''; setScreen('idle'); }
  }

  /* ---------- Start ---------- */
  navigate();
})();
